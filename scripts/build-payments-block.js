#!/usr/bin/env node
/*
 * Regenerate payments-block.js from the platform's current pasteable block.
 *
 * The repository used to carry payments-widget.js: a hand-written 734-line
 * re-implementation of that block. It drifted — by the time the platform had
 * grown a cart (per-row Add, a basket pill, one multi-line checkout), the fork
 * still only knew how to buy a single item, and no one noticed because nothing
 * compared the two. This script exists so the block is COPIED, never rewritten:
 *
 *   node scripts/build-payments-block.js            # from the live platform
 *   node scripts/build-payments-block.js --from f   # from a saved docs page
 *
 * It pulls the block out of the platform's own docs page, substitutes the group
 * slug, replaces the hard-coded BASE with the resolver below, and writes
 * payments-block.js. Re-run it whenever the platform ships a new block; the
 * diff is then the platform's changes, not ours.
 */
const fs = require('fs');
const path = require('path');

const GROUP = 'd8aaaa-batch_threadline';
const DOCS = 'http://localhost:3004/docs?group=' + GROUP;
const OUT = path.join(__dirname, '..', 'payments-block.js');

/* The one intentional deviation from the pasted block. The block hard-codes a
   single BASE; this site is served both locally (the `site` run entry, serve
   -l 5004, talking to the platform on localhost:3004) and, eventually, from a
   public host. Everything else below is the platform's code verbatim. */
const BASE_RESOLVER = `(function () {
    // Generated by scripts/build-payments-block.js — see that file.
    try {
      var o = String(window.D8A_BASE || '');
      if (o.indexOf('http://') === 0 || o.indexOf('https://') === 0) {
        while (o.length > 1 && o.slice(-1) === '/') o = o.slice(0, -1);
        return o;
      }
    } catch (e) {}
    try {
      var h = String(location.hostname || '').toLowerCase();
      if (location.protocol === 'file:' || h === 'localhost' || h === '127.0.0.1' ||
          h === '::1' || h === '[::1]' || h.slice(-10) === '.localhost') return "http://localhost:3004";
    } catch (e) {}
    // Not a working default: d8a.com is up but 404s this group's store API. Kept
    // so a deploy that forgets to say where the platform is degrades to the
    // block's own "could not be reached" panel instead of throwing — and says so.
    try {
      if (typeof console !== 'undefined' && console.warn) {
        console.warn('[d8a] No platform base set for this deployment; the shop will ' +
          'show as unreachable. Set window.D8A_BASE before this script.');
      }
    } catch (e) {}
    return "https://d8a.com";
  })()`;

function unescapeHtml(s) {
  return s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"')
          .replace(/&#x27;/g, "'").replace(/&amp;/g, '&');
}

function extract(html) {
  const cart = html.indexOf('YOUR OWN CART');
  if (cart === -1) throw new Error('docs page has no "YOUR OWN CART" marker — did the block change shape?');
  const start = html.lastIndexOf('Sell on your site', cart);
  let end = -1, p = start;
  for (;;) {
    const n = html.indexOf('&lt;/script&gt;', p + 1);
    if (n === -1 || n - start > 60000) break;
    end = n; p = n;
  }
  if (start === -1 || end === -1) throw new Error('could not find the block boundaries in the docs page');
  return unescapeHtml(html.slice(start, end)).replace(/^[^<]*/, '');
}

function build(block) {
  const lines = block.split('\n');
  const styleLine = lines.find(l => l.trim().startsWith('<style>'));
  const scriptAt = lines.findIndex(l => l.trim() === '<script>');
  if (!styleLine || scriptAt === -1) throw new Error('block is missing its <style> or <script>');
  const css = styleLine.trim().replace(/^<style>/, '').replace(/<\/style>$/, '');
  let js = lines.slice(scriptAt + 1).join('\n');

  const before = js;
  js = js.replace(/var GROUP = "[^"]*";/, 'var GROUP = ' + JSON.stringify(GROUP) + ';');
  js = js.replace(/var BASE = "[^"]*";/, 'var BASE = ' + BASE_RESOLVER + ';');
  if (js === before) throw new Error('BASE/GROUP substitution matched nothing — block shape changed');

  return `/* GENERATED FILE — DO NOT EDIT BY HAND.
 *
 * The D8A payments block for group ${GROUP}, copied from the
 * platform's own docs and written here by scripts/build-payments-block.js.
 * Regenerate with:  node scripts/build-payments-block.js
 *
 * Every page that sells carries <div id="group-store"></div> and includes this
 * file. The block owns the cart: per-row Add, a basket pill docked inside the
 * box, and ONE checkout for up to 20 lines. Pages that want their own basket
 * count read window.groupStoreCart.lines() and listen for "group-store:cart";
 * pages with their own cart hand it over with window.groupStoreCheckout(lines).
 *
 * Generated ${new Date().toISOString().slice(0, 10)}.
 */
(function () {
  var s = document.createElement('style');
  s.textContent = ${JSON.stringify(css)};
  document.head.appendChild(s);
})();

${js}`;
}

const fromArg = process.argv.indexOf('--from');
(async () => {
  let html;
  if (fromArg > -1) {
    html = fs.readFileSync(process.argv[fromArg + 1], 'utf8');
  } else {
    const res = await fetch(DOCS);
    if (!res.ok) throw new Error('docs fetch failed: HTTP ' + res.status);
    html = await res.text();
  }
  const out = build(extract(html));
  fs.writeFileSync(OUT, out);
  console.log('wrote ' + OUT + ' (' + out.split('\n').length + ' lines)');
})().catch(e => { console.error('FAILED: ' + e.message); process.exit(1); });
